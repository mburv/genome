/**
 * Pin the combo-tile palette so the first M4 chapter does not stall the UI (D-M4-18).
 * Usage: npx tsx scripts/generate-token-palette.ts [--check]
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { CORE_SIZE, computeTokenPalette } from '../src/engine/tokenColours.ts';

const OUT = new URL('../src/engine/tokenPalette.generated.ts', import.meta.url);

function render(): string {
  const pal = computeTokenPalette().slice(0, CORE_SIZE);
  const rows = pal.map((c) => {
    const lab = c.lab.map((n) => Number(n.toFixed(8)));
    return `  { bg: '${c.bg}', border: '${c.border}', fg: '${c.fg}', fgSoft: '${c.fgSoft}', contrast: ${Number(c.contrast.toFixed(8))}, lab: [${lab[0]}, ${lab[1]}, ${lab[2]}] }`;
  });
  return `/** Generated by scripts/generate-token-palette.ts — do not edit by hand. */\nimport type { TokenColour } from './tokenColours.ts';\n\nexport const TOKEN_PALETTE: readonly TokenColour[] = [\n${rows.join(',\n')},\n];\n`;
}

const next = render();
const check = process.argv.includes('--check');
if (check) {
  const prev = readFileSync(OUT, 'utf8');
  if (prev !== next) {
    console.error('tokenPalette.generated.ts is stale — run: npx tsx scripts/generate-token-palette.ts');
    process.exit(1);
  }
  console.log(`OK: pinned token palette prefix (${CORE_SIZE} colours)`);
} else {
  writeFileSync(OUT, next);
  console.log(`Wrote ${OUT.pathname} (first ${CORE_SIZE} of computeTokenPalette())`);
}
