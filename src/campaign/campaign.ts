import pack from './levels.generated.json';
import chapterPack from './chapters.generated.json';
import type { Interval, LevelDefinition } from '../engine/types.ts';

export interface LevelPack {
  campaignId: string;
  generatorVersion: string;
  /** M4: generator version of the token chapters (absent before M4). */
  tokenGeneratorVersion?: string;
  catalogueId?: string;
  /** Pinned dataset id per gene symbol. */
  datasets: Record<string, string>;
  levels: LevelDefinition[];
}

const m2 = pack as unknown as LevelPack;
const chapters = chapterPack as unknown as { catalogueId: string; generatorVersion: string; datasets: Record<string, string>; levels: LevelDefinition[] };
export const CAMPAIGN_ID = 'genome-m4-assembly';

/**
 * Pinned, immutable level pack (generated by scripts/generate-levels.ts): the 12-level sample campaign
 * and the 3 Enzyme labs (byte-identical to M3), followed by the M4 assembly chapters.
 */
export const LEVEL_PACK: LevelPack = {
  campaignId: CAMPAIGN_ID,
  generatorVersion: m2.generatorVersion,
  tokenGeneratorVersion: chapters.generatorVersion,
  catalogueId: chapters.catalogueId,
  datasets: { ...chapters.datasets, ...m2.datasets },
  levels: [...m2.levels, ...chapters.levels],
};
/** Every shipped level: the 12 campaign levels, the Enzyme-lab tutorials, then the assembly chapters. */
export const ALL_LEVELS: readonly LevelDefinition[] = LEVEL_PACK.levels;
/** The 12-level INS/HBB sample campaign (coverage, discovery and "Level N / 12" use only these). */
export const LEVELS: readonly LevelDefinition[] = ALL_LEVELS.filter((l) => !l.lab && !l.chapter);
/** M4 assembly chapter puzzles, grouped per gene in chapter order. */
export const CHAPTER_LEVELS: readonly LevelDefinition[] = ALL_LEVELS.filter((l) => l.chapter);
export const chapterOf = (symbol: string): LevelDefinition[] => CHAPTER_LEVELS.filter((l) => l.symbol === symbol);
/** Enzyme-lab tutorial levels (M3): one free use of their power, no coverage credit. */
export const LAB_LEVELS: readonly LevelDefinition[] = ALL_LEVELS.filter((l) => l.lab);
/** Sample challenges per gene in the demo; completing all unlocks the discovery card. */
export const SAMPLE_LEVELS_PER_GENE = 6;

export function levelById(id: string): LevelDefinition | undefined {
  return ALL_LEVELS.find((l) => l.id === id);
}

/** Sample-campaign levels of one gene (the 12-level demo). */
export const levelsForGene = (symbol: string, levels: readonly LevelDefinition[] = LEVELS): LevelDefinition[] => levels.filter((l) => l.symbol === symbol);

/** Size of the union of CDS intervals of completed levels for one gene. Replays never add duplicate coverage. */
export function coveredBases(completedIds: readonly string[], symbol: string, levels: readonly LevelDefinition[] = LEVELS): number {
  const intervals: Interval[] = levels
    .filter((l) => !l.lab && l.symbol === symbol && completedIds.includes(l.id))
    .flatMap((l) => l.sourceIntervals)
    .sort((a, b) => a.start - b.start);
  let total = 0;
  let end = -1;
  for (const iv of intervals) {
    const start = Math.max(iv.start, end);
    if (iv.end > start) total += iv.end - start;
    end = Math.max(end, iv.end);
  }
  return total;
}

export const sampleBases = (symbol: string, levels: readonly LevelDefinition[] = LEVELS): number =>
  coveredBases(levelsForGene(symbol, levels).map((l) => l.id), symbol, levels);

/**
 * Discovery (separate from assembly): all of a gene's sample challenges complete (INS/HBB demo route),
 * or — for every catalogue gene — the first puzzle of its assembly chapter complete.
 */
export const isDiscovered = (completedIds: readonly string[], symbol: string, levels: readonly LevelDefinition[] = LEVELS): boolean => {
  const own = levelsForGene(symbol, levels);
  if (own.length > 0 && own.every((l) => completedIds.includes(l.id))) return true;
  const opener = CHAPTER_LEVELS.find((l) => l.symbol === symbol && l.chapter!.part === 1);
  return !!opener && completedIds.includes(opener.id);
};
